"""Build all output formats from graph.json and research/*.md.

Outputs (in ./out):
  - index.html      interactive graph (vis-network, data + dossiers + resources embedded)
  - graph.json      validated copy of the data
  - neo4j.cypher    import script for Neo4j (12 canonical predicates)
  - obsidian/       vault with one note per node, [[wikilinks]], external resources, and tactical field playbooks

Usage:  python build.py
"""
from __future__ import annotations

import json
import re
import shutil
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).parent
SRC = ROOT / "graph.json"
OUT = ROOT / "out"
TEMPLATE = ROOT / "template.html"
RESEARCH_DIR = ROOT / "research"

BOOK_FOLDERS = {
    "htma": "01 How to Measure Anything",
    "ta": "02 The Trusted Advisor",
    "mom": "03 The Mom Test",
    "pp": "04 The Pyramid Principle",
    "bps": "05 Bulletproof Problem Solving",
    "sw": "06 Switch",
    "fc": "07 Flawless Consulting",
    "cdh": "08 Continuous Discovery Habits",
    "fde": "99 FDE Synthesis",
}

CANONICAL_PREDICATES = {
    "APPLIES",
    "SYNTHESIZES",
    "FEEDS",
    "MITIGATES",
    "CAUSES",
    "HAS_STEP",
    "HAS_COMPONENT",
    "USES",
    "ANALOGOUS_TO",
    "MEASURES",
    "FROM_BOOK",
    "AUTHORED",
}


def load_dossiers() -> dict[str, dict[str, str]]:
    """Load research/<book>.md and extract full markdown + tactical sections."""
    dossiers: dict[str, dict[str, str]] = {}
    if not RESEARCH_DIR.exists():
        return dossiers
    for md_file in sorted(RESEARCH_DIR.glob("*.md")):
        key = md_file.stem
        text = md_file.read_text(encoding="utf-8")
        # Extract from section 3 (Step-by-Step Toolkits) through section 5 (Field Playbook)
        m = re.search(r"(## 3\..*)", text, flags=re.DOTALL)
        tactical = m.group(1).strip() if m else text
        dossiers[key] = {
            "full": text,
            "tactical": tactical,
        }
    return dossiers


def load() -> dict:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    ids = [n["id"] for n in data["nodes"]]
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        raise SystemExit(f"Duplicate node ids: {sorted(dupes)}")
    idset = set(ids)
    bad = [e for e in data["edges"] if e["source"] not in idset or e["target"] not in idset]
    if bad:
        raise SystemExit(f"Edges with unknown nodes: {bad}")
    non_canonical = {e["relation"] for e in data["edges"]} - CANONICAL_PREDICATES
    if non_canonical:
        raise SystemExit(f"Non-canonical edge predicates found: {sorted(non_canonical)}")
    linked = {e["source"] for e in data["edges"]} | {e["target"] for e in data["edges"]}
    orphans = idset - linked
    if orphans:
        print(f"WARNING orphan nodes: {sorted(orphans)}")
    return data


def safe_name(label: str) -> str:
    name = label.replace("/", "-")
    name = re.sub(r'[\\:*?"<>|#^\[\]]', "", name)
    return re.sub(r"\s+", " ", name).strip()


def build_html(data: dict, dossiers: dict[str, dict[str, str]]) -> None:
    tpl = TEMPLATE.read_text(encoding="utf-8")
    enriched = dict(data)
    enriched["dossiers"] = dossiers
    payload = json.dumps(enriched, ensure_ascii=False).replace("</", "<\\/")
    (OUT / "index.html").write_text(tpl.replace("__GRAPH_DATA__", payload), encoding="utf-8")


def build_cypher(data: dict) -> None:
    lines = [
        "// Generated by build.py — run in Neo4j Browser or cypher-shell",
        "// Uses 12 canonical edge predicates: " + ", ".join(sorted(CANONICAL_PREDICATES)),
        "MATCH (n:KGNode) DETACH DELETE n;",
        "CREATE CONSTRAINT kg_id IF NOT EXISTS FOR (n:KGNode) REQUIRE n.id IS UNIQUE;",
        "",
    ]
    for n in data["nodes"]:
        props = ", ".join(
            f"{k}: {json.dumps(n[k], ensure_ascii=False)}" for k in ("id", "label", "type", "book", "description")
        )
        lines.append(f"CREATE (:KGNode:{n['type']} {{{props}}});")
    lines.append("")
    for e in data["edges"]:
        lines.append(
            f"MATCH (a:KGNode {{id: {json.dumps(e['source'])}}}), (b:KGNode {{id: {json.dumps(e['target'])}}}) "
            f"CREATE (a)-[:{e['relation']}]->(b);"
        )
    lines += [
        "",
        "// Example queries:",
        "// 1. Cross-book insights and what they synthesize:",
        "// MATCH (x:CrossInsight)-[:SYNTHESIZES]->(c) RETURN x, c;",
        "// 2. Path from a Mom Test concept to an FDE practice:",
        "// MATCH p=shortestPath((a {id:'mom_past_specifics'})-[*]-(b:FDEPractice)) RETURN p;",
        "// 3. All techniques that MITIGATE pitfalls across the 8 books:",
        "// MATCH (t)-[:MITIGATES]->(p:Pitfall) RETURN t.label, t.book, p.label, p.book;",
    ]
    (OUT / "neo4j.cypher").write_text("\n".join(lines) + "\n", encoding="utf-8")


def build_obsidian(data: dict, dossiers: dict[str, dict[str, str]]) -> None:
    vault = OUT / "obsidian"
    books = data["meta"]["books"]
    names = {n["id"]: safe_name(n["label"]) for n in data["nodes"]}
    outgoing, incoming = defaultdict(list), defaultdict(list)
    for e in data["edges"]:
        outgoing[e["source"]].append(e)
        incoming[e["target"]].append(e)

    resources_by_node = defaultdict(list)
    resources_by_book = defaultdict(list)
    node_by_id = {n["id"]: n for n in data["nodes"]}
    for r in data.get("resources", []):
        nid = r["node_id"]
        resources_by_node[nid].append(r)
        if nid in node_by_id:
            resources_by_book[node_by_id[nid]["book"]].append(r)

    for n in data["nodes"]:
        folder = vault / BOOK_FOLDERS[n["book"]]
        folder.mkdir(parents=True, exist_ok=True)
        tags = [f"type/{n['type']}", f"book/{n['book']}"]
        body = [
            "---",
            f"id: {n['id']}",
            f"type: {n['type']}",
            f"book: \"{books[n['book']]}\"",
            "tags: [" + ", ".join(tags) + "]",
            "---",
            f"# {n['label']}",
            "",
            n["description"],
            "",
        ]

        # Direct external resources for this node (or book-level resources if this is the Book node)
        node_res = list(resources_by_node.get(n["id"], []))
        if n["type"] == "Book":
            seen_urls = {r["url"] for r in node_res}
            for r in resources_by_book.get(n["book"], []):
                if r["url"] not in seen_urls:
                    node_res.append(r)
                    seen_urls.add(r["url"])

        if node_res:
            body.append("## External Resources")
            for r in node_res:
                kind = r.get("kind", "resource")
                body.append(f"- [{r['title']}]({r['url']}) _({kind})_")
            body.append("")

        if outgoing[n["id"]]:
            body.append("## Relations")
            for e in outgoing[n["id"]]:
                body.append(f"- **{e['relation']}** → [[{names[e['target']]}]]")
            body.append("")
        if incoming[n["id"]]:
            body.append("## Referenced by")
            for e in incoming[n["id"]]:
                body.append(f"- [[{names[e['source']]}]] **{e['relation']}** → this")
            body.append("")

        # Inject tactical dossier into the Book note, or link back to the Book's Field Playbook
        bkey = n["book"]
        if n["type"] == "Book" and bkey in dossiers:
            body.append("---")
            body.append("")
            body.append(dossiers[bkey]["full"])
            body.append("")
        elif bkey in dossiers and f"book_{bkey}" in names:
            book_note_name = names[f"book_{bkey}"]
            body.append("## Field Playbook & Tactical Scripts")
            body.append(
                f"See the complete chapter map, conversation scripts, and FDE deployment playbook in [[{book_note_name}#3. Step-by-Step Toolkits for a Deployed Strategist|{book_note_name}]]."
            )
            body.append("")

        (folder / f"{names[n['id']]}.md").write_text("\n".join(body), encoding="utf-8")

    index = ["# Knowledge Graph — Index", "", data["meta"]["source"], ""]
    for key, folder in BOOK_FOLDERS.items():
        index.append(f"## {books[key]}")
        for n in sorted((x for x in data["nodes"] if x["book"] == key), key=lambda x: (x["type"], x["label"])):
            index.append(f"- [[{names[n['id']]}]] — _{n['type']}_")
        index.append("")
    (vault / "00 Index.md").write_text("\n".join(index), encoding="utf-8")


def main() -> None:
    data = load()
    dossiers = load_dossiers()
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    (OUT / "graph.json").write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    build_html(data, dossiers)
    build_cypher(data)
    build_obsidian(data, dossiers)
    print(
        f"OK: {len(data['nodes'])} nodes, {len(data['edges'])} edges, "
        f"{len(data.get('resources', []))} resources, {len(dossiers)} dossiers -> {OUT}"
    )


if __name__ == "__main__":
    main()
