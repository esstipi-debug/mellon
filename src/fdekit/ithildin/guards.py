"""Deterministic guardrails and cryptographic safe-staging with HMAC-SHA256.

The Ithildin Pattern:
Protection remains silent and invisible during nominal operations.
It only "illuminates" (rejects, halts, and produces an auditable trace) when
an agent or integration attempts a mutation that violates contracts, lacks idempotency,
or attempts writing to a transactional system without a verified rollback plan.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timezone
from enum import Enum
import hashlib
import hmac
import json
from typing import Any, Mapping


class RiskLevel(str, Enum):
    """Operational risk level of a proposed staging action."""

    READ = "READ"  # Read-only, zero risk on database
    REVERSIBLE = "REVERSIBLE"  # Compensable write (e.g. create draft, soft reserve)
    IRREVERSIBLE = "IRREVERSIBLE"  # Destructive or financial mutation (e.g. cancel invoice, move physical stock)


@dataclass(frozen=True)
class StagingAction:
    """Immutable action proposal generated by an agent or pipeline before touching production."""

    action_id: str
    risk_level: RiskLevel
    target_system: str
    payload: Mapping[str, Any]
    idempotency_key: str
    timestamp_utc: str
    rollback_plan: Mapping[str, Any] | None = None

    def __post_init__(self) -> None:
        if not self.action_id:
            raise ValueError("action_id cannot be empty")
        if not self.target_system:
            raise ValueError("target_system cannot be empty")
        if not self.idempotency_key:
            raise ValueError("idempotency_key cannot be empty: all actions must be idempotent")
        if not self.timestamp_utc:
            raise ValueError("timestamp_utc cannot be empty: strict temporal audit required")

    def canonical_bytes(self) -> bytes:
        """Deterministic canonical serialization for signature verification."""
        normalized = {
            "action_id": self.action_id,
            "risk_level": self.risk_level.value,
            "target_system": self.target_system,
            "payload": self.payload,
            "idempotency_key": self.idempotency_key,
            "timestamp_utc": self.timestamp_utc,
            "rollback_plan": self.rollback_plan,
        }
        return json.dumps(normalized, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")


@dataclass(frozen=True)
class StagingVerdict:
    """Deterministic verdict of staging evaluation."""

    approved: bool
    code: str
    reason: str
    audit_hash: str
    evaluated_at_utc: str


class IthildinGuard:
    """Deterministic validation and signing engine for agents and integrations."""

    def __init__(self, secret_key: bytes) -> None:
        if not secret_key or len(secret_key) < 16:
            raise ValueError("secret_key must have at least 16 bytes of entropy for HMAC-SHA256")
        self._secret = secret_key
        self._committed_keys: set[str] = set()
        self._audit_ledger: list[StagingVerdict] = []

    def sign_action(self, action: StagingAction) -> str:
        """Generates the HMAC-SHA256 token cryptographically signing the staging action."""
        raw = action.canonical_bytes()
        sig = hmac.new(self._secret, raw, hashlib.sha256).hexdigest()
        return f"ithildin-v1-{sig}"

    def verify_signature(self, action: StagingAction, token: str) -> bool:
        """Verifies if the token matches the exact action using constant-time comparison."""
        if not token.startswith("ithildin-v1-"):
            return False
        expected_token = self.sign_action(action)
        return hmac.compare_digest(token, expected_token)

    def evaluate_and_commit(self, action: StagingAction, token: str) -> StagingVerdict:
        """Evaluates action against deterministic guardrails.

        If approved, the idempotency key is consumed in the in-memory ledger.
        If rejected, the action is illuminated (rejected) with clear provenance.
        """
        now_utc = datetime.now(timezone.utc).isoformat()
        audit_hash = hashlib.sha256(action.canonical_bytes()).hexdigest()

        # 1. Cryptographic signature verification
        if not self.verify_signature(action, token):
            verdict = StagingVerdict(
                approved=False,
                code="FORBIDDEN_INVALID_SIGNATURE",
                reason="HMAC token mismatch or payload was tampered with.",
                audit_hash=audit_hash,
                evaluated_at_utc=now_utc,
            )
            self._audit_ledger.append(verdict)
            return verdict

        # 2. Idempotency check
        if action.idempotency_key in self._committed_keys:
            verdict = StagingVerdict(
                approved=False,
                code="REJECTED_DUPLICATE_IDEMPOTENCY",
                reason=f"Idempotency key '{action.idempotency_key}' has already been consumed.",
                audit_hash=audit_hash,
                evaluated_at_utc=now_utc,
            )
            self._audit_ledger.append(verdict)
            return verdict

        # 3. Mandatory reversibility guardrail
        if action.risk_level == RiskLevel.IRREVERSIBLE and not action.rollback_plan:
            verdict = StagingVerdict(
                approved=False,
                code="REJECTED_IRREVERSIBLE_WITHOUT_ROLLBACK",
                reason="IRREVERSIBLE actions strictly require an executable rollback_plan.",
                audit_hash=audit_hash,
                evaluated_at_utc=now_utc,
            )
            self._audit_ledger.append(verdict)
            return verdict

        # Approved and committed
        self._committed_keys.add(action.idempotency_key)
        verdict = StagingVerdict(
            approved=True,
            code="APPROVED_FOR_WRITEBACK",
            reason="Action deterministically verified with tamper-proof signature and rollback contingency.",
            audit_hash=audit_hash,
            evaluated_at_utc=now_utc,
        )
        self._audit_ledger.append(verdict)
        return verdict

    @property
    def audit_ledger(self) -> list[StagingVerdict]:
        """Immutable record of emitted verdicts."""
        return list(self._audit_ledger)
